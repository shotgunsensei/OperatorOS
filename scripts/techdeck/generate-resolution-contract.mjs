import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const read = name => readFileSync(resolve(root, name), 'utf8').replace(/\r\n/g, '\n');
const schema = JSON.parse(read('docs/techdeck/machine-evidence-export.schema.json'));
const prompt = read('docs/prompts/MSP_RESOLUTION_CLOSEOUT_PROMPT.md');
const shortcut = read('docs/prompts/MSP_RESOLUTION_CLOSEOUT_SHORTCUT.md');
const template = JSON.parse(prompt.match(/Use this schema:\n\n([\s\S]*?)\n\nRULES FOR MACHINE_EVIDENCE_EXPORT:/u)?.[1] ?? 'null');
if (schema.properties.schema_version.const !== '1.0' || template?.schema_version !== '1.0') {
  throw new Error('Resolution contract version mismatch');
}
if (JSON.stringify(Object.keys(template)) !== JSON.stringify(Object.keys(schema.properties))) {
  throw new Error('Resolution schema must cover every canonical top-level field in order');
}

function typeFor(node) {
  if ('const' in node) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(value => JSON.stringify(value)).join(' | ');
  const types = Array.isArray(node.type) ? node.type : [node.type];
  return types.map(type => {
    if (type === 'null') return 'null';
    if (type === 'integer' || type === 'number') return 'number';
    if (type === 'string' || type === 'boolean') return type;
    if (type === 'array') return `Array<${typeFor(node.items ?? {})}>`;
    if (type === 'object') {
      if (!node.properties) return 'Record<string, unknown>';
      return `{\n${Object.entries(node.properties).map(([key, value]) =>
        `  ${JSON.stringify(key)}${node.required?.includes(key) ? '' : '?'}: ${typeFor(value)};`).join('\n')}\n}`;
    }
    return 'unknown';
  }).join(' | ');
}

const header = '// Generated by scripts/techdeck/generate-resolution-contract.mjs --write. Do not edit.\n';
const outputs = new Map([
  ['packages/sdk/src/techdeck-resolution.ts', `${header}
export const MACHINE_EVIDENCE_SCHEMA_VERSION = '1.0' as const;
export const MACHINE_EVIDENCE_EXPORT_TYPE = 'msp_incident_closeout' as const;
export const machineEvidenceExportSchema = ${JSON.stringify(schema, null, 2)} as const;
/** Unknown extension fields remain untrusted and are preserved only in screened source. */
export type MachineEvidenceExport = ${typeFor(schema)};
export type ResolutionConfidence = 'CONFIRMED' | 'HIGH' | 'MODERATE' | 'LOW' | 'UNKNOWN';
export type ResolutionClaimKind = 'reported_fact' | 'supported_conclusion' | 'hypothesis' | 'unverified' | 'pending_validation';
`],
  ['apps/api/src/generated/techdeck-resolution-contract.ts', `${header}
export const ticketCompletionPrompt = ${JSON.stringify(prompt)};
export const ticketCompletionShortcut = ${JSON.stringify(shortcut)};
export const machineEvidenceTemplate = ${JSON.stringify(template, null, 2)} as const;
export const ticketCompletionPromptSha256 = '${createHash('sha256').update(prompt).digest('hex')}';
`],
]);
for (const [file, content] of outputs) {
  if (process.argv.includes('--write')) {
    mkdirSync(dirname(resolve(root, file)), { recursive: true });
    writeFileSync(resolve(root, file), content, 'utf8');
  } else if (read(file) !== content) {
    throw new Error(`Resolution contract is stale: ${file}. Run node scripts/techdeck/generate-resolution-contract.mjs --write`);
  }
}
console.log(`Resolution v1.0 contract ${process.argv.includes('--write') ? 'generated' : 'verified'} (${outputs.size} artifacts).`);
